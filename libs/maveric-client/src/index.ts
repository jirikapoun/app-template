import type React from 'react'
import type { z, ZodType } from 'zod'


// React 19's ReactNode includes Promise, so ComponentType would accept async components,
// which suspend and can't be rendered by the synchronous renderToString
type SyncComponent<Props> = (props: Props) => Exclude<React.ReactNode, Promise<unknown>>
type View<P> = SyncComponent<P> & {
  displayName?: string
}

interface ClientEntry {
  /** URL of the module */
  url: string
  /** URLs of the modules to preload when the entry is used, usually the entry itself and the chunks it imports */
  preload: string[]
  /** URLs of the stylesheets used by the entry */
  css: string[]
}

// manifest of the client-side code, generated by the `maveric()` Vite plugin as `virtual:maveric/manifest`
// and used by the server to inject the code into the rendered pages
interface ClientManifest {
  /** browser runtime, which hydrates the rendered view */
  runtime: ClientEntry
  /** client entries of the views, keyed by the view components */
  views: Map<unknown, ClientEntry>
  /** HTML to be injected at the end of <head> */
  head: string
  /** HTML to be injected at the end of <body> */
  body: string
}

// data the server passes to the browser runtime to hydrate the rendered view
interface Payload {
  /** URL of the view module */
  view: string
  /** props the view has been rendered with */
  props: unknown
}

/** id of the <script type="application/json"> element containing the payload */
const PAYLOAD_ELEMENT_ID = '__maveric'

const view = <PropsSchema extends ZodType>(component: SyncComponent<z.infer<PropsSchema>>) =>
  component as View<z.infer<PropsSchema>>

export {
  PAYLOAD_ELEMENT_ID,
  view,
}

export type {
  ClientEntry,
  ClientManifest,
  Payload,
  View,
}
