import type React from 'react'
import type { z, ZodType } from 'zod'


// React 19's ReactNode includes Promise, so ComponentType would accept async components,
// which suspend and can't be rendered by the synchronous renderToString
type SyncComponent<Props> = (props: Props) => Exclude<React.ReactNode, Promise<unknown>>
type View<P> = SyncComponent<P> & {
  displayName?: string
}

interface ClientEntry {
  /** URL of the module */
  url: string
  /** URLs of the modules to preload when the entry is used, usually the entry itself and the chunks it imports */
  preload: string[]
  /** URLs of the stylesheets used by the entry */
  css: string[]
}

// manifest of the client-side code, generated by the `maveric()` Vite plugin as `virtual:maveric/manifest`
// and used by the server to inject the code into the rendered pages
interface ClientManifest {
  /** browser runtime, which hydrates the rendered view */
  runtime: ClientEntry
  /** client entries of the views, keyed by the view components */
  views: Map<unknown, ClientEntry>
  /** HTML to be injected at the end of <head> */
  head: string
  /** HTML to be injected at the end of <body> */
  body: string
  /**
   * HTML with the stylesheets of a view, to be injected at the end of <head>, only during development,
   * where the entries have no `css`, so that the page is styled before its scripts run
   */
  styles?(entry: ClientEntry): Promise<string>
}

// data the server passes to the browser runtime to hydrate the rendered view
interface Payload {
  /** URL of the view module */
  view: string
  /** props the view has been rendered with */
  props: unknown
}

/** id of the <script type="application/json"> element containing the payload */
const PAYLOAD_ELEMENT_ID = '__maveric'

/** custom HMR events exchanged between the dev server and the browser runtime */
const HMR_EVENTS = {
  /** sent by the runtime once it has hydrated a view, so that it can be updated without reloading the page */
  hydrated: 'maveric:hydrated',
  /** sent by the dev server when modules used only on the server have changed */
  serverUpdate: 'maveric:server-update',
} as const

const view = <PropsSchema extends ZodType>(component: SyncComponent<z.infer<PropsSchema>>) =>
  component as View<z.infer<PropsSchema>>

// callbacks registered while a view is being rendered on the server, a module-level registry is enough,
// because views are rendered synchronously, one at a time
let insertedHtmlCallbacks: Array<() => string> | null = null

/**
 * Registers a callback returning HTML for the end of <head>, such as styles collected while rendering on the server.
 * The callback runs once the view has been rendered; in the browser, nothing happens. Every call registers
 * the callback, like Next.js' hook of the same name.
 */
const useServerInsertedHTML = (callback: () => string) => {
  insertedHtmlCallbacks?.push(callback)
}

/** renders a view on the server, together with the HTML its components register with `useServerInsertedHTML()` */
const renderWithInsertedHTML = (render: () => string) => {
  const previousCallbacks = insertedHtmlCallbacks
  const callbacks: Array<() => string> = []
  insertedHtmlCallbacks = callbacks
  try {
    const html = render()
    return { html, insertedHtml: callbacks.map(callback => callback()).join('') }
  } finally {
    insertedHtmlCallbacks = previousCallbacks
  }
}

export {
  HMR_EVENTS,
  PAYLOAD_ELEMENT_ID,
  renderWithInsertedHTML,
  useServerInsertedHTML,
  view,
}

export type {
  ClientEntry,
  ClientManifest,
  Payload,
  View,
}
